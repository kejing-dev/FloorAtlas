#!/usr/bin/env python
"""Floor Atlas icon (design `icon`): chart-teal #0B7FA0 tile; a sand-coloured abstract landmass, two faint
graticule arcs, one white footprint and the yellow crosshair dot beside it. No text.

Writes, from one set of shapes (108-unit viewport of the adaptive icon):
  res/drawable/ic_launcher_foreground.xml   (vector, safe zone 66)
  res/drawable/icon_3d_layer_0/1.png + sdf  (PICO 3D icon layers)
  [export.png]                              512 x 512 flat icon (tile + glyph)

    python tools/make_icon.py [export.png]
"""
import math
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
S = 1024
K = S / 108.0
TEAL = (11, 127, 160, 255)
SAND = (233, 201, 139, 255)
WHITE = (255, 255, 255, 255)
ARC = (255, 255, 255, 64)
YELLOW = (255, 210, 63, 255)


def bezier(p0, p1, p2, p3, n=16):
    out = []
    for k in range(1, n + 1):
        t = k / n
        a = (1 - t) ** 3
        b = 3 * (1 - t) ** 2 * t
        c = 3 * (1 - t) * t * t
        d = t ** 3
        out.append((a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0], a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1]))
    return out


def land():
    segs = [
        ((26, 44), (31, 30), (52, 25), (66, 30)),
        ((66, 30), (80, 35), (85, 49), (78, 58)),
        ((78, 58), (71, 66), (75, 77), (62, 82)),
        ((62, 82), (49, 87), (33, 81), (29, 70)),
        ((29, 70), (25, 60), (22, 53), (26, 44)),
    ]
    pts = [segs[0][0]]
    for s in segs:
        pts += bezier(*s)
    return pts


def ellipse(cx, cy, rx, ry, rot_deg=0.0, n=40):
    a = math.radians(rot_deg)
    out = []
    for k in range(n):
        t = 2 * math.pi * k / n
        x, y = rx * math.cos(t), ry * math.sin(t)
        out.append((cx + x * math.cos(a) - y * math.sin(a), cy + x * math.sin(a) + y * math.cos(a)))
    return out


def arc_band(cx, cy, rx, ry, t0, t1, width, n=40):
    """A stroked elliptic arc as a closed polygon."""
    outer, inner = [], []
    for k in range(n + 1):
        t = math.radians(t0 + (t1 - t0) * k / n)
        outer.append((cx + (rx + width / 2) * math.cos(t), cy + (ry + width / 2) * math.sin(t)))
        inner.append((cx + (rx - width / 2) * math.cos(t), cy + (ry - width / 2) * math.sin(t)))
    return outer + inner[::-1]


SHAPES = [
    (arc_band(54, -134, 90, 200, 67, 113, 1.8), ARC),
    (arc_band(150, 54, 110, 70, 146, 214, 1.8), ARC),
    (land(), SAND),
    (ellipse(51.5, 48, 7.2, 10.5, -12), WHITE),
    (ellipse(55.5, 67, 5.6, 7.2, -12), WHITE),
    (ellipse(67, 72, 3.6, 3.6), YELLOW),
]


def hexcol(c):
    return "#%02X%02X%02X%02X" % (c[3], c[0], c[1], c[2])


def vector():
    paths = []
    for pts, col in SHAPES:
        d = "M" + " L".join("%.2f,%.2f" % p for p in pts) + "Z"
        paths.append(f'    <path android:fillColor="{hexcol(col)}" android:pathData="{d}" />')
    xml = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- generated by tools/make_icon.py: landmass, graticule arcs, footprint, crosshair dot (design icon) -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        + "\n".join(paths)
        + "\n</vector>\n"
    )
    with open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write(xml)


def tile():
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    ImageDraw.Draw(im).rounded_rectangle((40, 40, S - 40, S - 40), radius=220, fill=TEAL)
    return im


def front():
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    for pts, col in SHAPES:
        layer = Image.new("RGBA", (S, S), (0, 0, 0, 0))
        ImageDraw.Draw(layer).polygon([(x * K, y * K) for x, y in pts], fill=col)
        im = Image.alpha_composite(im, layer)
    return im


def alpha_white(im):
    w = Image.new("RGBA", im.size, (255, 255, 255, 0))
    w.putalpha(im.split()[3])
    return w


def main():
    vector()
    l0, l1 = tile(), front()
    draw = os.path.join(RES, "drawable")
    l0.save(os.path.join(draw, "icon_3d_layer_0.png"))
    l1.save(os.path.join(draw, "icon_3d_layer_1.png"))
    alpha_white(l0).save(os.path.join(draw, "icon_3d_sdf_0.png"))
    alpha_white(l1).save(os.path.join(draw, "icon_3d_sdf_1.png"))
    if len(sys.argv) > 1:
        full = Image.new("RGBA", (S, S), TEAL)
        Image.alpha_composite(full, l1).resize((512, 512), Image.LANCZOS).convert("RGB").save(sys.argv[1])
    print("icon written")


if __name__ == "__main__":
    main()
